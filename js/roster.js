(function () {
  var classmates = window.SHS86_CLASSMATES.slice();
  var gridEl = document.getElementById("roster-grid-container");
  var emptyEl = document.getElementById("roster-empty");
  var countEl = document.getElementById("roster-count");
  if (!gridEl) return;

  function lastNameOf(name) {
    var parts = name.replace(".", "").split(" ");
    var last = parts[parts.length - 1];
    if (["Jr", "Sr", "II", "III"].indexOf(last) !== -1) last = parts[parts.length - 2];
    return last;
  }
  classmates.sort(function (a, b) {
    return lastNameOf(a.name).toLowerCase().localeCompare(lastNameOf(b.name).toLowerCase());
  });

  function initialsOf(name) {
    var parts = name.replace(/[^A-Za-z ]/g, "").split(" ").filter(Boolean);
    return ((parts[0] && parts[0][0]) || "") + ((parts[parts.length - 1] && parts[parts.length - 1][0]) || "");
  }
  function escapeHtml(s) {
    var map = {
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#39;"
    };
    return String(s).replace(/[&<>"']/g, function (c) { return map[c]; });
  }
  function avatarHtml(c) {
    if (c.notPictured || !c.photo) return initialsOf(c.name).toUpperCase();
    return '<img src="' + c.photo + '" alt="' + escapeHtml(c.name) + '" loading="lazy" width="120" height="150" onerror="this.parentElement.textContent=\'' + initialsOf(c.name) + '\'">';
  }

  function renderGrid(list) {
    gridEl.innerHTML = "";
    if (emptyEl) emptyEl.style.display = list.length ? "none" : "block";
    if (countEl) countEl.textContent = list.length === classmates.length
      ? list.length + " classmates"
      : list.length + " of " + classmates.length + " classmates";
    list.forEach(function (c) {
      var col = document.createElement("div");
      col.className = "col-6 col-md-4 col-lg-3";
      var badges = "";
      if (c.inMemoriam) badges += '<div class="in-memoriam-badge">In memoriam</div>';
      if (c.notPictured) badges += '<div class="not-pictured-badge">Not pictured, 1986</div>';
      col.innerHTML =
        '<div class="profile-card">' +
          '<div class="profile-avatar">' + avatarHtml(c) + "</div>" +
          "<h3>" + escapeHtml(c.name) + "</h3>" +
          '<div class="profile-meta">' + escapeHtml(c.role || "Class of 1986") + "</div>" +
          badges +
          '<button type="button" class="btn-view-profile" data-slug="' + c.slug + '">View profile</button>' +
        "</div>";
      gridEl.appendChild(col);
    });
  }

  function applyFilters() {
    var q = (document.getElementById("roster-search").value || "").trim().toLowerCase();
    var rangeBtn = document.querySelector(".filter-chip.active");
    var range = rangeBtn ? rangeBtn.getAttribute("data-range") : "all";
    var filtered = classmates.filter(function (c) {
      if (q && c.name.toLowerCase().indexOf(q) === -1) return false;
      if (range === "all") return true;
      if (range === "remembered") return !!c.inMemoriam;
      var l = lastNameOf(c.name).toLowerCase().charAt(0);
      if (range === "a-g") return l >= "a" && l <= "g";
      if (range === "h-m") return l >= "h" && l <= "m";
      if (range === "n-s") return l >= "n" && l <= "s";
      if (range === "t-z") return l >= "t" && l <= "z";
      return true;
    });
    renderGrid(filtered);
  }

  document.getElementById("roster-search").addEventListener("input", applyFilters);
  document.querySelectorAll("#roster-filters .filter-chip").forEach(function (btn) {
    btn.addEventListener("click", function () {
      document.querySelectorAll("#roster-filters .filter-chip").forEach(function (b) { b.classList.remove("active"); });
      btn.classList.add("active");
      applyFilters();
    });
  });
  renderGrid(classmates);

  var current = null;
  var modalEl = document.getElementById("profileModal");
  var modal = modalEl ? new bootstrap.Modal(modalEl) : null;

  function openProfile(slug) {
    var c = classmates.filter(function (x) { return x.slug === slug; })[0];
    if (!c || !modal) return;
    current = c;
    document.getElementById("pd-avatar").innerHTML = avatarHtml(c);
    document.getElementById("pd-name").textContent = c.name;
    var role = c.role || "Class of 1986";
    if (c.notPictured) role += " · Not pictured in the 1986 yearbook";
    document.getElementById("pd-role").textContent = role;

    var bio = document.getElementById("pd-bio");
    if (c.bio) {
      bio.textContent = c.bio;
    } else if (c.inMemoriam) {
      bio.innerHTML = 'Remembered with the class on the <a href="memorial.html">Memorial page</a>.';
    } else {
      bio.innerHTML = '<span class="field-empty">Life updates live here once a classmate sends one in. If this is you, use the button below.</span>';
    }
    var updateBtn = document.getElementById("pd-update");
    if (updateBtn) updateBtn.hidden = !!c.inMemoriam;
    modal.show();
  }

  document.addEventListener("click", function (e) {
    var btn = e.target.closest(".btn-view-profile");
    if (btn) openProfile(btn.getAttribute("data-slug"));
  });

  var updateBtn = document.getElementById("pd-update");
  if (updateBtn) {
    updateBtn.addEventListener("click", function () {
      var name = current ? current.name : "";
      if (window.SHS86_LIB && window.SHS86_LIB.openWriteIn) {
        var cfg = window.SHS86 || {};
        window.SHS86_LIB.openWriteIn({
          title: "Update this classmate page",
          subject: "Class of '86 — update for " + name,
          formUrl: cfg.forms && cfg.forms.claimProfile,
          lead: "The committee will add this to the roster so every classmate can see it — not just on your phone.",
          body: "Hi — this is " + name + ". I'd like to update my classmate page.\n\nWhere I live now:\nWhat I've been up to:\nFamily:\n"
        });
        return;
      }
    });
  }
})();
